"""Render the drills report as Markdown from the drill results."""

from __future__ import annotations

from .findings import FINDINGS
from .params import Params


def _s(d: dict, unit: str) -> str:
    return (f"median {d['median']} {unit}, 95th percentile {d['p95']} {unit}, "
            f"max {d['max']} {unit} (n = {d['n']})")


def _intro(r: dict) -> list[str]:
    m = r["meta"]
    return [f"# Drills report, {m['date']}", "",
            "Software-simulation conformance report (no physical on-chip lock).", "",
            f"Generated by `python -m harness.fsp.drills` on {m['started']} ({m['platform']}, Python "
            f"{m['python']}); runtime {m['runtime_s']} s.", "",
            "**How to read it.** Every number below is a demo measurement: software devices on "
            "a simulated clock, with cadences the drills set and name. Each is compared with the "
            "appendix target it tests, and each target is a placeholder (PH-A), a design target "
            "(DT) or a value SPEC.md adds (PH-S). A drill tests the protocol's logic and the "
            "prototype's code. It says nothing about silicon, fleets or real rates. Findings "
            "appear where a drill produced them and again in section 7.", ""]


def _tamper(r: dict, p: Params) -> list[str]:
    t = r["tamper"]
    return ["## 1. Time to detect tampering on an online device", "",
            f"Target: under {p.t_tamper_detect // 60} minutes to the public log entry (PH-A); "
            f"fail-closed events logged within {p.t_failclosed_log} s (DT).", "",
            f"- Seeded tamper events: {t['of']}, one per device. Cadences (demo values): device "
            f"self-check every {t['cadences']['device_self_check_s']} s, carrier forwarding every "
            f"{t['cadences']['carrier_forward_s']} s.",
            f"- Physical event to log entry: {_s(t['event_to_log_s'], 's')}.",
            f"- Device detection to log entry, as the daily recheck sees it: "
            f"{_s(t['detection_to_log_s'], 's')}.",
            f"- Logged within 1 minute: {t['within_1_min']} of {t['of']}. Recheck verdicts: "
            f"{t['recheck']}. Every tampered device failed closed and no other device did: "
            f"{t['each_device_failed_closed']}.", "",
            "**Finding P6.** SPEC.md sets no device self-check period, and the recheck can only "
            "measure from the device's own detection time, which the fail-closed event carries. "
            "The gap between the physical event and detection is the self-check period, and in "
            "this drill it is the difference between the two rows above. The spec should set a "
            "self-check period and say which interval T_TAMPER_DETECT covers.", "",
            "The result shows that the logging path meets the target under these cadences. The "
            "cadences are inputs, so the drill does not show how fast real sensors or carriers "
            "are.", ""]


def _silent(r: dict, p: Params) -> list[str]:
    s = r["silent"]["modes"]
    rows = ["| Mode | Hours to fail-closed | Reason | Minutes to missed signal |",
            "| - | - | - | - |"]
    names = {"offline": "Fully offline", "time_only": "Heartbeats and renewals cut, time "
             "reachable", "inbound_open": "Only heartbeats hidden; roots still arrive"}
    for key, label in names.items():
        m = s[key]
        rows.append(f"| {label} | {_s(m['hours_to_fail_closed'], 'h')} | "
                    f"{', '.join(m['reasons'])} | max {m['minutes_to_missed']['max']} |")
    return ["## 2. Longest a silent device keeps running", "",
            f"Target: {p.renewal_validity // 3600} hours of renewal validity plus a "
            f"{p.time_allowance // 3600}-hour allowance, "
            f"{p.t_silent // 3600} hours in all (PH-A). Missed signal within "
            f"{p.t_missed // 60} minutes (PH-S). Silence starts at a random point in the epoch; "
            f"the drill steps every {r['silent']['step_s']} s, so minute figures are that coarse.",
            "", *rows, "",
            "**Finding P3.** The device rules make the two parts of T_SILENT alternatives, "
            "and no mode adds them. A fully offline device also loses its time quorum and stops "
            "at the "
            "72-hour allowance. A device that hides its heartbeats while its roots still arrive "
            "runs longest, because good standing admits a device heard within the last epoch: "
            "renewal validity plus one epoch. No mode came near the sum. The targets table "
            "should state the bound per mode.", ""]


def _effect(r: dict, p: Params) -> list[str]:
    e = r["effect"]
    return ["## 3. Time from a valid order to effect", "",
            f"Target: under {p.t_effect // 60} minutes from `effective_from` (PH-A).", "",
            f"- A halt reached {e['devices_in_scope']} devices polling every "
            f"{e['poll_period_s']} s (PH-S) at random phases; the notice lead was "
            f"{e['notice_lead_s']} s (PH-S). One device stayed offline.",
            f"- Effective time to applied receipt: {_s(e['effective_to_receipt_min'], 'min')}.",
            f"- The offline device was flagged by the missing-receipt comparison: "
            f"{e['offline_device_flagged_missing_receipt']}.",
            f"- Receipts backed by a prior logged, quorum-signed order: "
            f"{e['receipts_backed_by_prior_logged_order']} of {e['receipts']} (target 100 "
            "percent, DT).", "",
            "Under these settings the poll period bounds the effect time, so the target holds "
            "whenever T_POLL is shorter than T_EFFECT. Proof delivery on a real network is not "
            "measured.", ""]


def _lapse(r: dict) -> list[str]:
    c, f, fh = r["lapse_cut"], r["lapse_file"], r["false_halts"]
    return ["## 4. Correlated lapse and false-halt accounting", "",
            f"Every renewal path to {c['devices']} devices at {c['sites']} sites was cut at once "
            "while the devices kept reporting to the seats and reaching the time servers.", "",
            f"- Devices failed closed: {c['failed_closed']} of {c['devices']}, first at "
            f"{c['first_lapse_h']} h and last at {c['last_lapse_h']} h after the cut.",
            f"- Stale-renewal warning at {c['stale_renewal_warning_h']} h, "
            f"{c['warning_lead_h']} h before the first lapse (T_LAPSE_WARN is 72 h, PH-S).",
            f"- All devices restored {c['restored_within_h_after_path_returns']} h after the "
            "path returned.",
            f"- Same cut, renewals carried by file: {f['failed_closed']} of {f['devices']} "
            "failed closed.", "",
            "**Finding P7.** SPEC.md warns dependents when a device misses two roots. A cut "
            "renewal path leaves every device in good standing, so that rule never fires. The "
            "prototype also warns when a heartbeat reports a renewal two or more epochs old, and "
            "that warning is the one this drill recorded.", "",
            "**Finding P8.** After the path returns, devices wait for the next daily root. Seats "
            "should re-deliver the latest root, or issue one out of cadence, when a path "
            "returns.", "",
            f"False-halt accounting: {fh['false_halt_events']} correlated event reaching "
            f"{fh['events'][0]['devices'] if fh['events'] else 0} devices, over "
            f"{fh['device_years_simulated']} simulated device-years. As a per-device rate that "
            f"is {fh['false_halts_per_10k_device_years']} per 10,000 device-years against a "
            "placeholder of under 1. The drill injected the outage, so the figure is no estimate "
            "of a real rate. It shows the cost ASSESSMENT.md H2 predicted: one cut past the "
            "validity window stops every device behind it, and FALSE_HALT_EVENTS records it as "
            "one event with its device count.", ""]


def _conformance(r: dict) -> list[str]:
    rows = ["| Drill | Pass | Facts |", "| - | - | - |"]
    for d in r["conformance"]:
        facts = "; ".join(f"{k}: {v}" for k, v in d.items() if k not in ("drill", "pass"))
        rows.append(f"| {d['drill']} | {'yes' if d['pass'] else 'NO'} | {facts} |")
    return ["## 5. Conformance drills", "",
            "Drills 1, 3 and 4 of SPEC.md section 16.2 are sections 1 to 4 above. Drills 2 and "
            "5 to 11 follow. Drills 12 to 15 came from the reviews of 25 September 2026; drill "
            "15 passes when it reproduces the draft 0.1 behavior its finding describes.", "",
            *rows, "", *_review_findings(r)]


def _review_findings(r: dict) -> list[str]:
    by = {d["drill"].split()[0]: d for d in r["conformance"]}
    out = []
    if "13" in by:
        d = by["13"]
        out += [f"**Finding P54.** In drill 13 four seats tried to revoke the other three "
                f"keys for compromise with no proof. The device refused the roster "
                f"({d['grab_without_proof']}). A holder's own request and a repudiation "
                f"signed by a recovery key revoked two keys with no seat signature, the breach "
                f"was recorded ({'; '.join(d['breach_recorded'])}), and the holder re-enrolled "
                f"with its recovery key alone ({d['reenrolled_by_recovery_key_alone']}). "
                f"Reserve activation after T_REENROL is not built.", ""]
    if "15" in by:
        d = by["15"]
        out += [f"**Finding P56.** In drill 15 every device took a listed firmware update. "
                f"{d['heartbeats_rejected_after_update']} of {d['devices']} heartbeats were "
                f"rejected under the new keys, and {d['updated_devices_in_next_root']} updated "
                f"devices stayed in the next root. Under draft 0.1 a fleet rollout lapses the "
                f"fleet unless a stable device identity carries it.", ""]
    return out


def _limits() -> list[str]:
    return ["## 6. What this report does not prove", "",
            "It does not show tamper resistance, red-team cost, fleet behavior, network "
            "behavior or real false-halt rates. The time servers, landmarks, sensors and "
            "carriers are simulated, and their cadences are inputs. A model wrote both the "
            "protocol code and these drills, so a pass here is not an independent recheck.", ""]


def _followup() -> list[str]:
    rows = ["| Finding | Where | What it says | What it changes | Alone |",
            "| - | - | - | - | - |"]
    rows += [f"| {i} | {w} | {s} | {c} | {a} |" for i, w, s, c, a in FINDINGS]
    return ["## 7. Findings, as a final follow-up", "",
            "Each finding is stated where it arises: in this report, in README.md or in a "
            f"module docstring. This table restates all {len(FINDINGS)}.", "",
            *rows, ""]


def render(r: dict, p: Params) -> str:
    parts = (_intro(r) + _tamper(r, p) + _silent(r, p) + _effect(r, p) + _lapse(r)
             + _conformance(r) + _limits() + _followup())
    return "\n".join(parts)
