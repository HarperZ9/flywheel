def _section_text(body: str, anchor: str, limit: int = 400) -> str:
    """Plain text after a heading, for search matching only."""
    at = body.find(f'id="{anchor}"')
    chunk = body[at:at + 4000] if at >= 0 else ""
    nxt = re.search(r"<h[1-6] ", chunk[10:])
    chunk = chunk[:nxt.start() + 10] if nxt else chunk
    return html.unescape(re.sub(r"<[^>]+>", " ", chunk))[:limit].lower()


def layout(title: str, body: str, page: str, index_json: str, ver: str) -> str:
    groups: dict = {}
    for group, label, _src, target in PAGES:
        groups.setdefault(group, []).append((label, target))
    nav = ['<input id="q" type="search" placeholder="Search" aria-label="Search the docs">',
           '<div id="hits" role="list"></div>']
    nav.append("<details open><summary>Contents</summary>")
    for group, items in groups.items():
        nav.append(f"<h2>{html.escape(group)}</h2>")
        for label, target in items:
            cur = ' aria-current="page"' if target == page else ""
            nav.append(f'<a href="{target}"{cur}>{html.escape(label)}</a>')
    nav.append("</details>")
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width, initial-scale=1">'
            f"<title>{html.escape(title)} - Flywheel docs</title><style>{CSS}</style></head>"
            f'<body><div class="shell"><nav aria-label="Docs">{"".join(nav)}</nav>'
            f"<main>{body}<footer>Flywheel {ver}. Built from the repository at this version."
            f"</footer></main></div><script type=\"application/json\" id=\"idx\">{index_json}"
            f"</script><script>{SEARCH_JS}</script></body></html>")


def build(out: Path) -> list:
    """Write the site; returns the list of problems (empty on success)."""
    problems: list = []
    link_map = {src: page for _g, _t, src, page in PAGES if src}
    rendered, index = {}, []
    with tempfile.TemporaryDirectory() as home:
        cmd_md, missing = commands_markdown(home)
    problems += [f"command without usage text: flywheel {n}" for n in missing]
    for _group, title, src, page in PAGES:
        if src is None:
            md = cmd_md
        elif (ROOT / src).is_file():
            md = (ROOT / src).read_text(encoding="utf-8")
        else:
            problems.append(f"listed doc is missing: {src}")
            continue
        body, heads = convert(md, link_map=link_map, here=src or "")
        rendered[page] = (title, body)
        index += [[f"{title}: {text}", f"{page}#{anchor}", _section_text(body, anchor)]
                  for _lvl, text, anchor in heads]
    out.mkdir(parents=True, exist_ok=True)
    index_json = json.dumps(index).replace("</", "<\\/")
    ver = version()
    for page, (title, body) in rendered.items():
        (out / page).write_text(layout(title, body, page, index_json, ver), encoding="utf-8")
    for page, (_t, body) in rendered.items():
        for href in re.findall(r'href="([^"#:]+\.html)', body):
            if href not in rendered:
                problems.append(f"{page} links to a page that does not exist: {href}")
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(ROOT / "site" / "docs"))
    args = ap.parse_args(argv)
    problems = build(Path(args.out))
    for p in problems:
        print(f"[docs] {p}", file=sys.stderr)
    print(f"docs site written to {args.out}" if not problems else "docs site has problems")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
