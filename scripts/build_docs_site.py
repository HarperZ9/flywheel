PAGES = (  # (group, title, source, page)
    ("Start", "Overview", "README.md", "index.html"),
    ("Start", "Getting started", "GETTING-STARTED.md", "getting-started.html"),
    ("Coding", "flywheel code", "docs/CODE-SESSION.md", "code.html"),
    ("Coding", "Capture hooks for other agents", "docs/WRAPPER-HOOKS.md", "capture-hooks.html"),
    ("Verification", "Recheck a claim", "RECHECK.md", "recheck.html"),
    ("Verification", "Benchmarks", "docs/BENCHMARKS.md", "benchmarks.html"),
    ("Reference", "Commands", None, "commands.html"),
    ("Project", "Licensing", "docs/LICENSING.md", "licensing.html"),
    ("Project", "Support", "SUPPORT.md", "support.html"),
    ("Project", "Changelog", "CHANGELOG.md", "changelog.html"),
)


def version() -> str:
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    return re.search(r'^version\s*=\s*"(.+?)"', text, re.M).group(1)


def command_names() -> list:
    sys.path.insert(0, str(ROOT))
    from harness import cli_entry
    return sorted(set(cli_entry._PACKAGED) | set(cli_entry._UMBRELLA_USAGE))


def command_help(name: str, home: str) -> str:
    env = {**os.environ, "FLYWHEEL_HOME": home, "PYTHONPATH": str(ROOT)}
    with tempfile.TemporaryDirectory() as cwd:
        p = subprocess.run([sys.executable, "-c",
                            f"from harness.cli_entry import main; raise SystemExit(main({[name, '--help']!r}))"],
                           cwd=cwd, env=env, capture_output=True, text=True, timeout=60)
    return (p.stdout or p.stderr).strip()


def commands_markdown(home: str) -> "tuple[str, list]":
    missing: list = []
    parts = ["# Commands", "",
             "Every command below prints this text for `flywheel <command> --help`. "
             "The page is generated from the code at build time.", ""]
    for name in command_names():
        text = command_help(name, home)
        if "usage" not in text.lower():
            missing.append(name)
        parts += [f"## flywheel {name}", "", "```", text[:6000], "```", ""]
    return "\n".join(parts), missing


