"""build_docs_site.py -- build the Flywheel docs site from the repository.

    python scripts/build_docs_site.py --out site/docs

Standard library only. Renders a fixed list of repository docs to HTML pages
with one navigation, a heading search, and a command reference generated by
running `flywheel <command> --help` for every command, so the reference cannot
drift from the code. Fails (exit 1) when a listed doc is missing, an internal
link points at nothing, or a command prints no usage. The site is written to
--out; nothing is published by this script.
"""
