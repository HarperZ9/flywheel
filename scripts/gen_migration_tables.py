"""gen_migration_tables.py -- write docs/MIGRATING-2.0-SCHEMAS.md from its sources.

The 2.0 migration note needs two tables that must not drift from the code:
the receipt codes that changed, and every schema whose version moved. Both
are derived here and never typed by hand.

- Receipt codes: the string constants in `legacy_limits` and `derived_scope`
  of harness/receipt_scope.py, paired by position. The two functions test the
  same receipt fields in the same order.
- Schemas: the tables under "Schemas" in project-docs/SCOPE-MIGRATION.md, the
  checklist the rename was made from.

    python scripts/gen_migration_tables.py            # rewrite the page
    python scripts/gen_migration_tables.py --check    # exit 1 if it is stale

Standard library only.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "project-docs" / "SCOPE-MIGRATION.md"
CODES = ROOT / "harness" / "receipt_scope.py"
PAGE = ROOT / "docs" / "MIGRATING-2.0-SCHEMAS.md"
MOVE = re.compile(r"((?:[\w-]+ )?)v(\d+) -> v(\d+)")
OLD = "does_" + "not_prove"   # spelled apart: the scope gate reads this file too
STAYS = re.compile(r"^(unchanged|stays v\d+)\b")


def _codes(function: ast.FunctionDef, names: dict) -> list[str]:
    """Every code the function puts in its list, in source order: the items
    of the list it starts with and the argument of each `append`."""
    items = []
    for node in ast.walk(function):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.List):
            items += node.value.elts
        elif (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
              and node.func.attr == "append"):
            items += node.args
    found = []
    for item in items:
        if isinstance(item, ast.Constant) and isinstance(item.value, str):
            found.append((item.lineno, item.value))
        elif isinstance(item, ast.Name) and item.id in names:
            found.append((item.lineno, names[item.id]))
    return [value for _line, value in sorted(found)]


def code_pairs() -> list[tuple[str, str]]:
    """(1.x code, 2.0 code) for a receipt, in the order both lists use."""
    tree = ast.parse(CODES.read_text(encoding="utf-8"))
    names = {t.id: n.value.value for n in tree.body if isinstance(n, ast.Assign)
             for t in n.targets if isinstance(n.value, ast.Constant)}
    functions = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    old = _codes(functions["legacy_limits"], names)
    new = _codes(functions["derived_scope"], names)
    if len(old) != len(new) or not old:
        raise SystemExit(f"receipt_scope.py: {len(old)} old codes, {len(new)} new codes")
    return list(zip(old, new))


def _clean(cell: str) -> str:
    return cell.replace("`", "").replace("|", "/").strip()


def schema_rows() -> list[tuple[str, str, str]]:
    """(group, name, change) for every row of the record's schema tables."""
    text = RECORD.read_text(encoding="utf-8")
    section = text[text.index("\n## Schemas"):text.index("\n## Re-pins")]
    group, rows = "", []
    for line in section.splitlines():
        if line.startswith("### "):
            group = line[4:].strip()
        if not line.startswith("| ") or line.startswith(("| schema", "|---")):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        rows.append((group, _clean(cells[0]), cells[1]))
    return rows


def _moves(change: str) -> str:
    found = [f"{prefix}v{old} to v{new}" for prefix, old, new in MOVE.findall(change)]
    return ", ".join(dict.fromkeys(found))


def sort_rows(rows) -> tuple[list, list, list]:
    """(version moved, no version id, unchanged). Rows that are notes about
    another row, with none of the three shapes, are left out."""
    moved, bare, same = [], [], []
    for group, name, change in rows:
        if MOVE.search(change):
            moved.append((group, name, _moves(change)))
        elif name.lower().startswith("unversioned") or change.startswith("unversioned"):
            bare.append((group, name.split(":", 1)[-1].strip()))
        elif STAYS.match(change):
            same.append((group, name, STAYS.match(change).group(1)))
    return moved, bare, same


def render() -> str:
    moved, bare, same = sort_rows(schema_rows())
    count = sum(len(MOVE.findall(c)) for *_x, c in schema_rows())
    out = [
        "# Schema versions and codes changed in 2.0", "",
        "Generated by `scripts/gen_migration_tables.py` from",
        "`harness/receipt_scope.py` and `project-docs/SCOPE-MIGRATION.md`. Do not",
        "edit this page by hand; a test fails when it differs from its sources.",
        "It is the reference list for [Moving from 1.x to 2.0](MIGRATING-2.0.md).", "",
        "## Receipt codes", "",
        "A 1.x receipt (`flywheel.receipt/v3` and `v4`) lists limits under",
        f"`{OLD}`. A 2.0 receipt (`flywheel.receipt/v5`) lists what it covers",
        "under `scope`. Each row is one receipt field. The 1.x code is present when",
        "the limit applies, and the 2.0 code is present when the property holds, so",
        "for most rows a receipt that had the old code lacks the new one. The first",
        "row is the code every receipt carries, and the last row is present in both",
        "versions under the same condition.", "",
        f"| 1.x code in `{OLD}` | 2.0 code in `scope` |", "|---|---|"]
    out += [f"| `{old}` | `{new}` |" for old, new in code_pairs()]
    out += ["", "## Schemas whose version moved", "",
            f"{len(moved)} rows, {count} version moves. A writer in 2.0 emits only the "
            "new version. A reader", "accepts both and reads each with its own field name.", ""]
    group = None
    for g, name, change in moved:
        if g != group:
            out += ["" if group else None, f"### {g}", "", "| Schema | Version |", "|---|---|"]
            group = g
        out.append(f"| {name} | {change} |")
    out += ["", "## Records with no version id", "",
            "These carry no schema version. The field is renamed, and readers accept",
            "either name.", ""]
    out += [f"- {name}" for _g, name in bare]
    out += ["", "## Unchanged", "", "| Record | State |", "|---|---|"]
    out += [f"| {name} | {state} |" for _g, name, state in same]
    return "\n".join(line for line in out if line is not None) + "\n"


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in args:
        current = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{PAGE.relative_to(ROOT).as_posix()} is stale: run "
                  "python scripts/gen_migration_tables.py")
            return 1
        return 0
    PAGE.write_bytes(text.encode("utf-8"))
    print(f"wrote {PAGE.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
