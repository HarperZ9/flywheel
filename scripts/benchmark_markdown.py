"""benchmark_markdown.py, the text form of the benchmark surface.

Same record, same numbers, no styling. It lives beside the page builder
because the two renderers grow at different rates and the page builder is
already at the size limit. `build_benchmark_page.py` imports render_markdown
from here and writes what it returns to docs/BENCHMARKS.md.
"""

from __future__ import annotations

from typing import Any

from scripts.benchmark_shared import CELL, lede, wrap


def render_markdown(report: dict[str, Any], doc: dict[str, Any]) -> str:
    out = ["# Flywheel benchmarks", "",
           f"Seal `{report['result_sha256'][:32]}` on python "
           f"{report['python']}. Generated by "
           "`scripts/build_benchmark_page.py` from "
           "`docs/benchmarks/report.json`; do not edit by hand.", "",
           lede(report), "", "## What ran", "",
           "| suite | question | headline |", "| --- | --- | --- |"]
    for suite in report["suites"]:
        head = "; ".join(f"{k} {v}" for k, v in suite["headline"].items())
        out.append(f"| {suite['name']} | {suite['question']} | {head} |")

    # A caveat that lives only in the record lets a surface present a number
    # as cleaner than it is, so they are printed with the table they qualify.
    caveated = [(s["name"], s["caveats"]) for s in report["suites"]
                if s.get("caveats")]
    if caveated:
        out += ["", "### What those numbers do not show", ""]
        for name, caveats in caveated:
            out += [f"- **{name}.** {c}" for c in caveats]

    acc = next(s for s in report["suites"] if s["name"] == "accountability")
    out += ["", "## The falsifier", "",
            "A benchmark everything passes measures nothing. The strawman is a "
            "system with no receipts, scored on the same axes.", "",
            "| dimension | harness | strawman |", "| --- | --- | --- |"]
    for dim in acc["detail"]:
        straw = dim.get("strawman")
        out.append(f"| {dim['name']} | {dim['score']:.0%} | "
                   f"{'not scored' if straw is None else f'{straw:.0%}'} |")
    out += ["", f"Overall {acc['headline']['harness_overall']:.0%} against "
            f"{acc['headline']['strawman_overall']:.0%}. This "
            f"{acc['non_goal']}.", "", "## Against the field", "",
            "The Flywheel column is checked against this repository every time "
            "the matrix is read. The competitor columns are dated declarations "
            f"from public documentation, read on {doc['declared_on']}, and are "
            "not measurements taken here.", "",
            "| capability | flywheel | codex | cursor | claude code |",
            "| --- | --- | --- | --- | --- |"]
    unique = set(doc["summary"]["uniquely_witnessed"])
    for row in doc["rows"]:
        cells = " | ".join(CELL[row["competitors"][n]][1]
                           for n in ("codex", "cursor", "claude-code"))
        mark = " *" if row["key"] in unique else ""
        out.append(f"| {row['key']}{mark} | {row['flywheel'].lower()} | {cells} |")
    s = doc["summary"]
    out += ["", f"{len(doc['rows'])} rows, {s['witnessed']} witnessed, "
            f"{s['absent']} absent, {len(s['uniquely_witnessed'])} marked `*` "
            "because no listed peer declares them.", "",
            "## What was not measured", ""]
    for entry in report["not_run"]:
        out.append(f"- **{entry['suite']}.** Needs {entry['needs']}. "
                   f"`{entry['where']}`")
        if entry.get("standing_result"):
            out.append(f"  Standing result: {entry['standing_result']}")
    out += ["", "## Re-run it", "", "```bash",
            "python scripts/run_offline_benchmarks.py",
            "python scripts/build_benchmark_page.py", "```", ""]
    return "\n".join(out)


BEGIN = "<!-- benchmarks:begin"
END = "<!-- benchmarks:end -->"
def _accountability(report: dict[str, Any]) -> dict[str, Any]:
    return next(s for s in report["suites"]
                if s["name"] == "accountability")["headline"]


def render_readme_block(report: dict[str, Any], doc: dict[str, Any]) -> str:
    """The short form for the README, between the generated markers.

    The README is the first surface a reader sees, so it carries the headline,
    the falsifier, and the null, then sends the reader to the long document.
    The interval that includes zero is here rather than only in BENCHMARKS.md,
    because that is the number a reader is most likely to assume in our
    favour.
    """
    s = doc["summary"]
    acc = _accountability(report)
    m7 = next(e for e in report["not_run"] if e["suite"] == "m7 capability arms")
    paired = next(s["headline"] for s in report["suites"]
                  if s["name"] == "paired-replication")
    table = ["| suite | what it answers | headline |", "| --- | --- | --- |"]
    for suite in report["suites"]:
        head = "; ".join(f"{k} {v}" for k, v in suite["headline"].items())
        table.append(f"| {suite['name']} | {suite['question']} | {head} |")
    blocks = [
        wrap(f"{len(report['suites'])} suites run with no model endpoint and "
             "no network, so you get these numbers back on your own machine:"),
        "```bash\npython scripts/run_offline_benchmarks.py\n```",
        "\n".join(table),
        wrap(f"The strawman, a system with no receipts, scores "
              f"{acc['strawman_overall']:.0%} on the same axes. A benchmark "
              "that everything passes measures nothing."),
        wrap(f"Against the field: {len(doc['rows'])} capabilities, "
              f"{s['witnessed']} witnessed in this repository by a check that "
              f"runs every time the matrix is read, and "
              f"{len(s['uniquely_witnessed'])} that no listed peer declares. "
              "The competitor columns are dated readings of public "
              "documentation, not measurements taken here."),
        wrap("Full results, the matrix, and the measurements that were not "
              "taken: [docs/BENCHMARKS.md](docs/BENCHMARKS.md)."),
        wrap("One of those suites recomputes the project's only capability "
             "comparison, and it is negative: continued pretraining on the "
             f"workspace corpus moved general code completion "
             f"{paired['delta_points'] * 100:+.2f} percentage points "
             f"over {paired['tasks']} tasks, p = {paired['p_exact']:.2f}. "
             "It is here "
             "because a negative result published is worth more than a "
             "positive one withheld."),
        wrap("The arms benchmark is a separate instrument, "
             f"{m7['standing_result']}"),
    ]
    return "\n\n".join(blocks)


def splice_readme(current: str, block: str) -> str:
    """Put the generated block back between its markers, leaving the rest.

    Everything a person wrote stays. Only the text between the two comment
    markers is replaced, so the README cannot disagree with the record and a
    hand edit inside the block is reverted on the next build rather than
    silently kept.
    """
    if BEGIN not in current or END not in current:
        raise SystemExit("README.md lost its benchmarks markers")
    before = current[:current.index(BEGIN)]
    marker = current[current.index(BEGIN):]
    marker = marker[:marker.index("-->") + 3]
    after = current[current.index(END) + len(END):]
    return f"{before}{marker}\n{block}\n{END}{after}"
